#!/usr/bin/env python3
"""The stack's external names, for NET_API_PREFIX (include/net_rename.h).

  api_rename.py [--nm NM] --check LIB...   every external symbol the
                                           libraries define is in the header,
                                           under the header that declares it
  api_rename.py [--nm NM] --write LIB...   add those that are not

A project that already has a net_init() of its own, or carries another
stack with a tcp_write(), builds this one with -DNET_API_PREFIX=stcp_ (any
prefix): every function and object with external linkage is then renamed,
in the stack's sources and in every file that includes its headers.
net_rename.h lists the names in one section per header — the header that
declares them — and each header includes it, so a file is given the macros
of the headers it includes and no others: an application's own
http_server_init() is its own in a file that does not include http.h
(issue 10).  This script keeps the list whole.  CMake runs --check as the
test api_prefix_covers_every_symbol, in every configuration CI builds, so a
new public function fails it until the header is regenerated:

  cmake --build build && python3 scripts/api_rename.py --write build/libsmallest_tcp_*.a

--write only adds: names another platform or configuration defines stay.
"""

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "include", "net_rename.h")
LINE = re.compile(r"^#define (\w+) NET_API\(\1\)$", re.M)
SECTION = re.compile(r"^#if defined\((\w+)\) && !defined\(NET_RENAMED_\1\)$", re.M)
GUARD = re.compile(r"^#ifndef (\w+_H)\n#define \1$", re.M)
INCLUDE = '#include "net_rename.h"'
# The headers that may declare a name: the public ones, the drivers', and
# the private ones the sources share
DIRS = ("include", os.path.join("include", "driver"), "src")

TOP = """/**
 * @file net_rename.h
 * @brief The stack's external names under a prefix (NET_API_PREFIX).
 *
 * With NET_API_PREFIX defined — to stcp_, say, by -D or in NET_CONFIG_FILE
 * — every function and object of the stack with external linkage is
 * compiled, and called, under that prefix (net_init() is stcp_net_init()
 * to the linker), so that the stack links beside code that has such names
 * of its own.  The stack's sources and every file that includes its
 * headers must be compiled with the same NET_API_PREFIX.
 *
 * The names are macros for the prefixed ones, in one section per header:
 * each header includes this file after its include guard, and is given
 * the section of the names it declares.  A file has the macros of the
 * headers it includes, so there the plain names mean the stack's; the
 * names of a module whose header it does not include stay its own
 * (docs/design/configuration.md §7).  Types, macros and static inline
 * functions are not renamed: they collide only in a file that includes
 * both sets of headers.
 *
 * Generated by scripts/api_rename.py, which also checks it (the test
 * api_prefix_covers_every_symbol): do not edit the list by hand.
 */

/* No include guard: each header includes this file for its own section */

#include "net_config.h"

#ifdef NET_API_PREFIX

#ifndef NET_API
#define NET_API_CAT_(prefix, name) prefix##name
#define NET_API_CAT(prefix, name) NET_API_CAT_(prefix, name)
#define NET_API(name) NET_API_CAT(NET_API_PREFIX, name)
#endif
"""
BOTTOM = "\n#endif /* NET_API_PREFIX */\n"


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def headers():
    """{include guard: (path, text without comments)} of every header that
    can declare a name"""
    found = {}
    for d in DIRS:
        for name in sorted(os.listdir(os.path.join(ROOT, d))):
            path = os.path.join(d, name)
            if not name.endswith(".h") or path == os.path.join("include",
                                                               "net_rename.h"):
                continue
            text = read(os.path.join(ROOT, path))
            guard = GUARD.search(text)
            if guard:
                found[guard.group(1)] = (path, text)
    return found


def declarer(name, hdrs):
    """The include guard of the one header that declares @p name"""
    # at file scope, so not indented: a call in a static inline function is
    # no declaration
    decl = re.compile(r"^(\w[\w \t*]*[\s*])?%s\s*\(|^extern\b[^;]*\b%s\b" %
                      (name, name), re.M)
    which = [g for g, (_, text) in hdrs.items()
             if decl.search(re.sub(r"/\*.*?\*/", "", text, flags=re.S))]
    if len(which) != 1:
        sys.exit("%s is declared in %s: one header must declare it" %
                 (name, ", ".join(hdrs[g][0] for g in which) or "no header"))
    return which[0]


def listed():
    """{name: include guard of its section} as net_rename.h has them"""
    if not os.path.exists(HEADER):
        return {}
    names, section = {}, None
    for line in read(HEADER).splitlines():
        m = SECTION.match(line)
        if m:
            section = m.group(1)
            continue
        m = LINE.match(line)
        if m:
            names[m.group(1)] = section
    return names


def defined(nm, libs):
    """External symbols the libraries define, as C names."""
    names = set()
    for lib in libs:
        out = subprocess.run([nm, "-g", "--defined-only", lib], check=True,
                             capture_output=True, text=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) != 3:
                continue
            name = parts[2]
            if sys.platform == "darwin" and name.startswith("_"):
                name = name[1:]  # Mach-O's leading underscore
            names.add(name)
    return names


def main(argv):
    nm = "nm"
    if argv[:1] == ["--nm"]:
        nm, argv = argv[1], argv[2:]
    if len(argv) < 2 or argv[0] not in ("--check", "--write"):
        sys.exit(__doc__)
    have, found = listed(), defined(nm, argv[1:])
    prefix = os.environ.get("NET_API_PREFIX", "")
    if prefix:  # libraries built with the prefix: every symbol carries it
        bare = [n for n in sorted(found) if not n.startswith(prefix)]
        if bare:
            sys.exit("not renamed by NET_API_PREFIX (does its header include "
                     "net_rename.h?):\n  " + "\n  ".join(bare))
        found = {n[len(prefix):] for n in found}
    hdrs = headers()
    want = {n: declarer(n, hdrs) for n in set(have) | found}
    if argv[0] == "--check":
        problems = ["%s (not listed)" % n for n in sorted(found - set(have))]
        problems += ["%s (listed under %s, declared in %s)" %
                     (n, have[n], hdrs[want[n]][0])
                     for n in sorted(have) if have[n] != want[n]]
        problems += ["%s does not include net_rename.h" % hdrs[g][0]
                     for g in sorted(set(want.values()))
                     if INCLUDE not in hdrs[g][1]]
        if problems:
            sys.exit("include/net_rename.h is out of date (run "
                     "scripts/api_rename.py --write):\n  " +
                     "\n  ".join(problems))
        return
    with open(HEADER, "w", encoding="utf-8") as f:
        f.write(TOP)
        for guard in sorted(set(want.values()), key=lambda g: hdrs[g][0]):
            f.write("\n/* %s */\n" % hdrs[guard][0])
            f.write("#if defined(%s) && !defined(NET_RENAMED_%s)\n" %
                    (guard, guard))
            f.write("#define NET_RENAMED_%s\n" % guard)
            for name in sorted(n for n in want if want[n] == guard):
                f.write("#define %s NET_API(%s)\n" % (name, name))
            f.write("#endif\n")
        f.write(BOTTOM)
    for guard in sorted(set(want.values())):
        path, text = hdrs[guard]
        if INCLUDE not in text:  # after the include guard
            text = read(os.path.join(ROOT, path))
            m = GUARD.search(text)
            text = (text[:m.end()] + "\n\n" + INCLUDE +
                    " /* NET_API_PREFIX */" + text[m.end():])
            with open(os.path.join(ROOT, path), "w", encoding="utf-8") as f:
                f.write(text)
    print("%d names, %d new" % (len(want), len(found - set(have))))


if __name__ == "__main__":
    main(sys.argv[1:])
